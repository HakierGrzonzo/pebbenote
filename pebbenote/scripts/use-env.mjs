// Applies an environment from environments.json: writes src/ts/env.ts and sets
// the app's uuid and display name in package.json. Dev gets its own uuid so it
// installs next to prod, with separate localStorage (backend url and tokens).
import { readFileSync, writeFileSync } from "node:fs";

const name = process.argv[2] ?? "prod";
const environments = JSON.parse(readFileSync("environments.json", "utf8"));
const env = environments[name];
if (!env) {
  console.error(
    `Unknown environment "${name}", expected one of: ${Object.keys(environments).join(", ")}`,
  );
  process.exit(1);
}

// Allow one-off overrides, e.g. a LAN address when testing on a real phone
const backendUrl = process.env.PEBBENOTE_BACKEND_URL ?? env.backendUrl;
const issuer = process.env.PEBBENOTE_ISSUER ?? env.issuer;

writeFileSync(
  "src/ts/env.ts",
  `// generated by scripts/use-env.mjs (${name}) - do not edit
export const ENVIRONMENT = ${JSON.stringify(name)};
export const DEFAULT_BASE = ${JSON.stringify(backendUrl)};
export const ISSUER = ${JSON.stringify(issuer)};
`,
);

const pkg = JSON.parse(readFileSync("package.json", "utf8"));
pkg.pebble.uuid = env.uuid;
pkg.pebble.displayName = env.displayName;
writeFileSync("package.json", JSON.stringify(pkg, null, 2) + "\n");

console.log(`Using "${name}": ${backendUrl}, ${issuer}`);
